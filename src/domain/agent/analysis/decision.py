"""Decision LLM proposal schemas for agent contract models."""

from enum import StrEnum

from pydantic import Field

from src.domain.agent.common import ContractModel


class DecisionProposalStatus(StrEnum):
    """Status of the decision proposal produced by the LLM."""

    PROPOSED = "proposed"
    NEEDS_INPUT = "needs_input"


class TradeOff(ContractModel):
    """An explicit benefit versus cost trade-off between the preferred supplier and an alternative."""

    preferred_supplier_id: str = Field(min_length=1)
    alternative_supplier_id: str = Field(min_length=1)
    description: str = Field(min_length=1)


class DecisionProposal(ContractModel):
    """Structured proposal generated by Decision LLM presented to Buyer for review (HITL-2).

    Invariants per contract:
    - Synthesizes existing calculated artifacts; does not re-compute TCO.
    - References only suppliers present in the analysis input snapshot.
    - Directly transitions analysis to 'awaiting_buyer_review'.
    """

    status: DecisionProposalStatus
    preferred_supplier_id: str | None = None
    ranked_supplier_ids: list[str] = Field(default_factory=list)
    rationale: str = Field(min_length=1)
    tradeoffs: list[TradeOff] = Field(default_factory=list)
    input_artifact_ids: list[str] = Field(default_factory=list)


__all__ = [
    "DecisionProposal",
    "DecisionProposalStatus",
    "TradeOff",
]
