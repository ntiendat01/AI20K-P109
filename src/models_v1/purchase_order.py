"""Purchase Order aggregate schemas for models_v1."""

from enum import StrEnum

from pydantic import Field

from src.models_v1.common import ContractModel, Money, UtcDateTime


class POStatus(StrEnum):
    """Lifecycle status of a generated Purchase Order."""

    DRAFT = "draft"
    CANCELLED = "cancelled"


class PurchaseOrder(ContractModel):
    """PurchaseOrder aggregate entity generated upon Manager approval.

    Invariants per contract:
    - Generated by PurchaseOrderService, never directly by LLM.
    - shipping_amount is nullable (default None). It represents an unconfirmed
      or pending business calculation and must NEVER be silently converted to 0.00.
    """

    id: str = Field(min_length=1)
    tenant_id: str = Field(min_length=1)
    code: str = Field(min_length=1)
    pr_id: str = Field(min_length=1)
    approval_decision_id: str = Field(min_length=1)
    analysis_id: str = Field(min_length=1)
    snapshot_hash: str = Field(min_length=1)
    supplier_id: str = Field(min_length=1)
    quotation_revision_id: str = Field(min_length=1)
    subtotal: Money
    shipping_amount: Money | None = None
    tax_amount: Money
    total_amount: Money
    currency: str = Field(min_length=1)
    status: POStatus = POStatus.DRAFT
    approver_id: str = Field(min_length=1)
    approved_at: UtcDateTime
    created_at: UtcDateTime


class PurchaseOrderResponse(ContractModel):
    """Public API representation for GET /purchase-orders/{po_id}."""

    id: str
    code: str
    status: POStatus
    pr_id: str
    analysis_id: str
    snapshot_hash: str
    quotation_revision_id: str
    supplier_id: str
    subtotal: Money
    shipping_amount: Money | None = None
    tax_amount: Money
    total_amount: Money
    currency: str


__all__ = [
    "POStatus",
    "PurchaseOrder",
    "PurchaseOrderResponse",
]
